def exif_date(path):
    try:
        ex = Image.open(path).getexif()
        sub = ex.get_ifd(0x8769)
        d = sub.get(36867) or ex.get(306)
        if d:
            return d[:10].replace(":", "-")
    except Exception:
        pass
    return None

def save(im, path, long_side, q=80):
    im = im.copy()
    im.thumbnail((long_side, long_side), Image.LANCZOS)
    im.save(path, "WEBP", quality=q, method=6)
    return im.size

